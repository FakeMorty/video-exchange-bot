def format_nick_inline(name: str, style_id: int | None = None) -> str:
    """Форматирует ник для inline-режима."""
    if style_id is None or style_id not in STYLES:
        return name
    s = STYLES[style_id]
    return f"{s.inline_left}{name}{s.inline_right}"


def format_nick_card(name: str, style_id: int | None = None) -> str:
    """Форматирует ник для card-режима (профиль)."""
    if style_id is None or style_id not in STYLES:
        return name
    s = STYLES[style_id]
    return f"{s.card_top}\n   {name}\n{s.card_bottom}"


def style_label(style_id: int) -> str:
    """Человекочитаемое название стиля."""
    if style_id in STYLES:
        return STYLES[style_id].label
    return f"Стиль #{style_id}"


def style_inline_preview(style_id: int) -> str:
    """Короткий пример стиля с именем-заглушкой (для каталога)."""
    return format_nick_inline("Ник", style_id)


def styles_in_category(cat_id: int) -> list[_Style]:
    """Все стили заданной категории."""
    return STYLES_BY_CAT.get(cat_id, [])


def validate_style_id(style_id: int) -> bool:
    """Существующий id стиля?"""
    return style_id in STYLES
