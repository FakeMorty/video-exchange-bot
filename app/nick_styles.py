class _Style:
    """Один стиль никнейма — immutable."""
    __slots__ = ("id", "cat_id", "inline_left", "inline_right",
                 "card_top", "card_bottom", "label")

    def __init__(self, sid: int, raw: tuple):
        self.id = sid
        self.cat_id       = raw[0]
        self.inline_left  = raw[1]
        self.inline_right = raw[2]
        self.card_top     = raw[3]
        self.card_bottom  = raw[4]
        self.label        = raw[5]


STYLES: dict[int, _Style] = {}
STYLES_BY_CAT: dict[int, list[_Style]] = {c: [] for c in CATEGORIES}

for _i, _raw in enumerate(_RAW, start=1):
    _s = _Style(_i, _raw)
    STYLES[_i] = _s
    STYLES_BY_CAT[_raw[0]].append(_s)

del _i, _raw, _s

# Легаси-маппинг: color_nick → стиль 1, gold_nick → стиль 2
LEGACY_PERK_MAP: dict[str, int] = {
    "color_nick": 1,
    "gold_nick": 2,
}


